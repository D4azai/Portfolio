import { chromium } from 'playwright';
import AxeBuilder from '@axe-core/playwright';
import assert from 'node:assert/strict';
import { previewServer } from '../server/local.js';
import { resolve } from 'node:path';
const server=previewServer({root:resolve('dist')});
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const base=`http://127.0.0.1:${server.address().port}`;
const browser=await chromium.launch({channel:'msedge',headless:true});
try {
 const context=await browser.newContext({viewport:{width:1440,height:1000}}), page=await context.newPage();
 page.setDefaultTimeout(15000);
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base+'/#home');
 await page.waitForSelector('.hero-art .hologram-ready');
 await page.waitForFunction(()=>getComputedStyle(document.querySelector('.hero-atmosphere i')).animationPlayState==='running');
 await page.locator('.layer-button').filter({hasText:'Flow'}).click(); assert.equal(await page.locator('#home').getAttribute('data-hero-layer'),'flow');
 await page.getByRole('button',{name:'Pause character animation'}).click();
 assert.equal(await page.locator('.hero-atmosphere i').first().evaluate(e=>getComputedStyle(e).animationPlayState),'paused');
 await page.getByRole('button',{name:'Resume character animation'}).click();
 console.log('PASS hero lighting responds to layer selection and pauses with the robot');
 await page.locator('.cinematic-frame').scrollIntoViewIfNeeded();
 await page.waitForSelector('.cinematic-ready');
 await page.waitForTimeout(1800);
 await page.locator('.cinematic-section').screenshot({path:'artifacts/cinematic-desktop.png'});
 const stage=page.locator('.cinematic-viewport');
 await stage.scrollIntoViewIfNeeded(); const frame=await stage.getAttribute('data-frame'); await page.waitForFunction(previous=>document.querySelector('.cinematic-viewport').dataset.frame!==previous,frame);
 await page.getByRole('button',{name:'Explore the layers'}).click();
 await page.waitForFunction(()=>Number(document.querySelector('.cinematic-viewport').dataset.expansion)>.95);
 await page.locator('.cinematic-section').screenshot({path:'artifacts/cinematic-expanded.png'});
 await page.getByRole('button',{name:'Pause cinematic motion'}).click();
 const paused=await stage.getAttribute('data-frame'); await page.waitForTimeout(180); assert.equal(await stage.getAttribute('data-frame'),paused);
 const bounds=await stage.boundingBox(); const before=await stage.getAttribute('data-orbit');
 await page.mouse.move(bounds.x+bounds.width*.5,bounds.y+bounds.height*.5); await page.mouse.down(); await page.mouse.move(bounds.x+bounds.width*.7,bounds.y+bounds.height*.5,{steps:8}); await page.mouse.up();
 assert.notEqual(await stage.getAttribute('data-orbit'),before);
 await page.getByRole('button',{name:'Reset sculpture view'}).click(); assert.equal(await stage.getAttribute('data-orbit'),'0.200');
 await stage.focus(); await page.keyboard.press('ArrowRight'); assert.equal(await stage.getAttribute('data-orbit'),'0.380'); await page.keyboard.press('Home'); assert.equal(await stage.getAttribute('data-orbit'),'0.200');
 await page.getByRole('button',{name:'Bring it together'}).click(); assert.equal(await stage.getAttribute('data-expansion'),'0.00');
 await page.getByRole('button',{name:'Play cinematic motion'}).click();
 await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'})); await page.waitForTimeout(250);
 assert.equal(await stage.getAttribute('data-motion'),'paused');
 console.log('PASS cinematic rendering, expansion, drag, reset, pause, and offscreen suspension');
 await page.goto(base+'/about'); await page.waitForSelector('html.react-ready');
 await page.locator('.profile-desk').scrollIntoViewIfNeeded(); await page.waitForTimeout(500);
 const paperBounds=await page.locator('.studio-profile').boundingBox(); await page.mouse.move(paperBounds.x+paperBounds.width*.5,paperBounds.y+paperBounds.height*.5); await page.waitForTimeout(300);
 assert.equal(await page.locator('.profile-desk').getAttribute('data-pointer-active'),'true');
 const card=page.locator('.studio-profile'); assert.equal(await card.evaluate(e=>getComputedStyle(e).animationPlayState),'paused');
 await page.locator('.studio-people').screenshot({path:'artifacts/premium-papers.png'});
 await page.getByRole('button',{name:'Pause background motion'}).click();
 assert.equal(await card.evaluate(e=>getComputedStyle(e).animationPlayState),'paused');
 await page.getByRole('button',{name:'Resume background motion'}).click();
 await page.emulateMedia({reducedMotion:'reduce'});
 assert.equal(await card.evaluate(e=>getComputedStyle(e).animationName),'none');
 await page.goto(base+'/#home'); await page.locator('.cinematic-frame').scrollIntoViewIfNeeded(); await page.waitForSelector('.cinematic-ready');
 assert.equal(await stage.getAttribute('data-motion'),'paused');
 await page.getByRole('button',{name:'Explore the layers'}).click(); assert.equal(await stage.getAttribute('data-expansion'),'1.00');
 await page.setViewportSize({width:390,height:844}); await page.waitForTimeout(350);
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.locator('.cinematic-section').screenshot({path:'artifacts/cinematic-mobile.png'});
 const audit=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
 assert.deepEqual(audit.violations.map(v=>({id:v.id,targets:v.nodes.map(n=>n.target)})),[]);
 const gl=await browser.newContext({viewport:{width:390,height:844}});const fallback=await gl.newPage();
 await fallback.addInitScript(()=>{const original=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(type,...args){return type.includes('webgl')?null:original.call(this,type,...args)}});
 await fallback.goto(base+'/#home'); await fallback.locator('.cinematic-frame').scrollIntoViewIfNeeded(); await fallback.waitForTimeout(700);
 assert.equal(await fallback.locator('.cinematic-ready').count(),0); assert.equal(await fallback.locator('.cinematic-poster').isVisible(),true);
 assert.deepEqual(errors,[]);
 console.log('PASS paper hover and motion, ambient pause, reduced motion, mobile layout, accessibility, WebGL fallback, and browser errors');
} finally { await browser.close(); server.close(); }
